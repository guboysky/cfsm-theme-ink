const server = { id: 'one', name: 'Tokyo Edge', region: 'JP', server_group: 'Production', cpu: 12, cpu_cores: 4, ram_total: 4096, ram_used: 1024, disk_total: 80000, disk_used: 12000, swap_total: 2048, swap_used: 0, net_in_speed: 1024, net_out_speed: 512, net_rx: 90000, net_tx: 40000, arch: 'amd64', os: 'Debian', last_updated: Date.now(), ping_ct: 0, loss_ct: 0, ping_cu: null, loss_cu: null, ping_cm: false, loss_cm: false, ping: [{ ts: Date.now(), ct: 0, cu: null, cm: false }], loss: [{ ts: Date.now(), ct: 0, cu: null, cm: false }] }
async function mock(page, { isPublic = true, turnstile = false, loggedIn = false, timeout = 0, rejectOnce = false, nodes = 1, multiSite = false } = {}) {
  const calls = [], sockets = [], apiErrors = [], pageErrors = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await page.addInitScript(({ loggedIn }) => {
    if (loggedIn && location.pathname !== '/admin') localStorage.setItem('jwt_token', 'test-jwt')
    window.turnstile = { render: (element, options) => { element.innerHTML = '<button id="solve">Verify</button>'; element.querySelector('button').onclick = () => options.callback('test-turnstile'); return 'widget' }, remove: () => {}, reset: () => {} }
    document.addEventListener('test-hidden', () => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')) })
    document.addEventListener('test-visible', () => { Object.defineProperty(document, 'hidden', { configurable: true, value: false }); document.dispatchEvent(new Event('visibilitychange')) })
  }, { loggedIn })
  await page.route('**/flags/**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg"/>' }))
  await page.route('**/os-icons/**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg"/>' }))
  let rejected = false
  await page.route('**/api/**', async route => {
    const request = route.request(), url = new URL(request.url()), headers = request.headers()
    calls.push({ path: url.pathname, query: url.search, headers, method: request.method(), body: request.postDataJSON() })
    if (url.pathname === '/api/config') return route.fulfill({ json: { site_title: 'Ink Infrastructure', version: 'test', preferred_theme: 'dark', default_language: 'zh', is_public: isPublic, authorization: loggedIn, turnstile_enabled: turnstile, turnstile_site_key: 'test-key', frontend_ws_timeout_minutes: timeout, theme_options: {}, custom_ct_name: '电信', custom_cu_name: '联通' } })
    if (!isPublic && !headers.authorization) return route.fulfill({ status: 401, json: { error: 'Unauthorized' } })
    if (turnstile && ((!headers['x-turnstile-token'] && !headers['x-turnstile-verified']) || (rejectOnce && !rejected))) { rejected = true; return route.fulfill({ status: 403, json: { error: 'Turnstile' } }) }
    const verified = turnstile ? { turnstile_verified: 'cached-verified' } : {}
    if (url.pathname === '/api/servers') return route.fulfill({ json: { servers: Array.from({ length: nodes }, (_, index) => ({ ...server, id: multiSite ? url.hostname : index ? `node-${index}` : 'one', name: nodes === 1 ? server.name : ['Tokyo Edge', 'Singapore Core', 'Frankfurt Relay', 'Hong Kong Edge', 'Los Angeles', 'London Gateway'][index], cpu: 12 + index * 11, ram_used: 1024 + index * 350, server_group: index > 2 ? 'Development' : 'Production', region: ['JP', 'SG', 'DE', 'HK', 'US', 'GB'][index], last_updated: index === 5 ? Date.now() - 400000 : Date.now() })), stats: { total: nodes, online: nodes === 6 ? 5 : nodes, offline: nodes === 6 ? 1 : 0 }, sysConfig: { show_three_net_details: true }, ...verified } })
    if (url.pathname === '/api/server') return route.fulfill({ json: { ...server, ...verified } })
    if (url.pathname === '/api/history/all') return route.fulfill({ json: [{ ...server, timestamp: Date.now() - 10000 }, { ...server, cpu: 25, timestamp: Date.now() }] })
    if (url.pathname === '/api/theme_options') return route.fulfill({ json: { success: true, ...verified } })
    apiErrors.push(url.pathname); return route.fulfill({ status: 404 })
  })
  await page.routeWebSocket('**/api/ws?*', ws => {
    const entry = { ws, url: new URL(ws.url()), messages: [], closed: false }
    sockets.push(entry)
    ws.onMessage(message => entry.messages.push(JSON.parse(message)))
    ws.onClose(() => { entry.closed = true })
  })
  await page.route('**/admin', route => route.fulfill({ contentType: 'text/html', body: 'Built-in administration login' }))
  return { calls, sockets, apiErrors, pageErrors }
}
const count = (context, path) => context.calls.filter(call => call.path === path).length
for (const isPublic of [true, false]) for (const turnstile of [false, true]) {
  test(`contract: ${isPublic ? 'public' : 'private'} + Turnstile ${turnstile ? 'on' : 'off'}`, async ({ page }) => {
    const ctx = await mock(page, { isPublic, turnstile, loggedIn: !isPublic })
    await page.goto('/')
    if (turnstile) await page.locator('#solve').click()
    await expect(page.locator('.server-card')).toHaveCount(1)
    await expect.poll(() => ctx.sockets.length).toBe(1)
    expect(ctx.sockets[0].url.searchParams.get('subscribe')).toBe('all')
    await expect.poll(() => ctx.sockets[0].messages.length).toBe(1)
    expect(ctx.sockets[0].messages[0]).toEqual({ type: 'subscribe', scope: 'all', ids: ['one'] })
    expect(ctx.sockets[0].url.searchParams.has('token')).toBe(false)
    await expect(page.locator('.server-card')).toContainText('0 ms')
    await expect(page.locator('.server-card')).toContainText('超时')
    await expect(page.locator('.probe-row')).toHaveCount(2)
    await page.locator('.server-card').click()
    await expect(page.locator('.chart-card').first()).toBeVisible()
    await expect.poll(() => ctx.sockets.length).toBe(2)
    expect(ctx.sockets[0].closed).toBe(true)
    expect(ctx.sockets[1].url.searchParams.get('subscribe')).toBe('one')
    expect(ctx.calls.find(call => call.path === '/api/history/all').query).toBe('?id=one&hours=0.167')
    await page.locator('select').selectOption('6')
    await expect.poll(() => count(ctx, '/api/history/all')).toBe(2)
    await page.locator('.back-link').click()
    await expect(page.locator('.server-card')).toBeVisible()
    expect(count(ctx, '/api/config')).toBe(1); expect(count(ctx, '/api/servers')).toBe(1)
    expect(ctx.apiErrors).toEqual([]); expect(ctx.pageErrors).toEqual([])
    if (turnstile) {
      expect(ctx.calls.find(call => call.path === '/api/servers').headers['x-turnstile-token']).toBe('test-turnstile')
      expect(ctx.calls.find(call => call.path === '/api/server').headers['x-turnstile-verified']).toBe('cached-verified')
      await page.reload()
      await expect(page.locator('.server-card')).toBeVisible()
      await expect(page.locator('#solve')).toHaveCount(0)
      expect(ctx.calls.filter(call => call.path === '/api/servers').at(-1).headers['x-turnstile-verified']).toBe('cached-verified')
    } else expect(ctx.calls.every(call => !call.headers['x-turnstile-token'] && !call.headers['x-turnstile-verified'])).toBe(true)
  })
}
